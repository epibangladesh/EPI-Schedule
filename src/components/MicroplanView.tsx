import React, {useMemo, useRef, useState} from 'react';
import html2canvas from 'html2canvas';
import * as XLSX from 'xlsx';
import {
  FileSpreadsheet,
  Image as ImageIcon,
  Pencil,
  RotateCcw,
  Save,
  Table2,
  X,
} from 'lucide-react';
import {
  dayShortBn,
  dayShortEn,
  displayCentersConfig,
  executionOrderCodes,
  formatNum,
  getAutoGeneratedHolidays,
  pairingRules,
  toBnNum,
  toIsoDateInput,
  translations,
} from '../data/epiData';
import type {
  CenterNamesMap,
  DayPairKey,
  Language,
  MicroplanRow,
  OverridesMap,
} from '../types';

interface MicroplanViewProps {
  lang: Language;
  centerNames: CenterNamesMap;
  allOverrides: Record<string, OverridesMap>;
  onSaveMicroplan: (
    year: number,
    yearOverrides: OverridesMap,
    updatedCenters: CenterNamesMap
  ) => void;
  onResetYear: (year: number) => void;
  onNotify: (msg: string, type?: 'success' | 'error' | 'info') => void;
}

export const MicroplanView: React.FC<MicroplanViewProps> = ({
  lang,
  centerNames,
  allOverrides,
  onSaveMicroplan,
  onResetYear,
  onNotify,
}) => {
  const t = translations[lang];
  const [selectedYear, setSelectedYear] = useState<number>(2026);
  const [pairKey, setPairKey] = useState<DayPairKey>('mon-thu');
  const [isEditMode, setIsEditMode] = useState<boolean>(false);

  const [draftOverrides, setDraftOverrides] = useState<OverridesMap | null>(null);
  const [draftCenters, setDraftCenters] = useState<CenterNamesMap | null>(null);

  const [editingCenter, setEditingCenter] = useState<{code: string; name: string} | null>(null);
  const [editingSession, setEditingSession] = useState<{
    code: string;
    monthIdx: number;
    dateStr: string;
  } | null>(null);
  const [confirmResetOpen, setConfirmResetOpen] = useState(false);

  const printAreaRef = useRef<HTMLDivElement | null>(null);
  const tableRef = useRef<HTMLTableElement | null>(null);

  const activeOverrides: OverridesMap = useMemo(
    () => draftOverrides ?? allOverrides[`epi_overrides_${selectedYear}`] ?? {},
    [draftOverrides, allOverrides, selectedYear]
  );

  const activeCenters: CenterNamesMap = useMemo(
    () => draftCenters ?? centerNames,
    [draftCenters, centerNames]
  );

  const holidays = useMemo(() => getAutoGeneratedHolidays(selectedYear), [selectedYear]);

  const planRows: MicroplanRow[] = useMemo(() => {
    const isHoliday = (dateObj: Date) => {
      if (dateObj.getDay() === 5) return true;
      const dateStr = toIsoDateInput(dateObj);
      return holidays.some((h) => h.date === dateStr);
    };

    const rows: MicroplanRow[] = displayCentersConfig.map((c) => ({
      code: c.code,
      name: activeCenters[c.code] || c.name,
      dates: new Array<Date>(12),
    }));

    let minDatesMap: Record<string, Date> = {};
    const primaryPair = pairingRules[pairKey];

    for (let m = 0; m < 12; m++) {
      const lastDay = new Date(selectedYear, m + 1, 0).getDate();
      const workingDays: number[] = [];
      for (let d = 1; d <= lastDay; d++) {
        if (!isHoliday(new Date(selectedYear, m, d))) workingDays.push(d);
      }

      const monthSessions: Record<string, Date> = {};
      const usedDates = new Set<number>();

      for (const code of executionOrderCodes) {
        const manualIso = activeOverrides[code]?.[m];
        if (manualIso) {
          const [y, mo, da] = manualIso.split('-').map(Number);
          const manualDate = new Date(y, mo - 1, da);
          monthSessions[code] = manualDate;
          usedDates.add(manualDate.getDate());
          continue;
        }

        let minStartDay = 1;
        const minTarget = minDatesMap[code];
        if (
          minTarget &&
          minTarget.getFullYear() === selectedYear &&
          minTarget.getMonth() === m
        ) {
          minStartDay = minTarget.getDate();
        }

        let candidateDays = workingDays.filter((d) => d >= minStartDay && !usedDates.has(d));
        if (candidateDays.length === 0) {
          candidateDays = workingDays.filter((d) => !usedDates.has(d));
        }

        const chosenDay =
          candidateDays.find((d) => primaryPair.includes(new Date(selectedYear, m, d).getDay())) ??
          candidateDays[0] ??
          workingDays[0] ??
          1;

        monthSessions[code] = new Date(selectedYear, m, chosenDay);
        usedDates.add(chosenDay);
      }

      const nextMinMap: Record<string, Date> = {};
      for (const code of executionOrderCodes) {
        const curr = monthSessions[code];
        const minNext = new Date(curr);
        minNext.setDate(minNext.getDate() + 28);
        nextMinMap[code] = minNext;
        const idx = rows.findIndex((r) => r.code === code);
        if (idx >= 0) rows[idx].dates[m] = curr;
      }
      minDatesMap = nextMinMap;
    }

    return rows;
  }, [selectedYear, pairKey, holidays, activeOverrides, activeCenters]);

  const enterEditMode = () => {
    setDraftOverrides(structuredClone(allOverrides[`epi_overrides_${selectedYear}`] ?? {}));
    setDraftCenters({...centerNames});
    setIsEditMode(true);
  };

  const cancelEditMode = () => {
    setDraftOverrides(null);
    setDraftCenters(null);
    setIsEditMode(false);
  };

  const handleSave = () => {
    onSaveMicroplan(selectedYear, activeOverrides, activeCenters);
    setDraftOverrides(null);
    setDraftCenters(null);
    setIsEditMode(false);
    onNotify(
      lang === 'bn'
        ? 'বাৎসরিক মাইক্রোপ্লানের তথ্য সেভ ও সিংক হয়েছে।'
        : 'Annual microplan saved & synced.',
      'success'
    );
  };

  const handleDownloadImage = async () => {
    const area = printAreaRef.current;
    const table = tableRef.current;
    if (!area || !table) return;

    const prevOverflow = area.style.overflowX;
    const prevWidth = area.style.width;
    const fullWidth = Math.max(table.scrollWidth + 32, 1150);

    area.style.overflowX = 'visible';
    area.style.width = `${fullWidth}px`;

    try {
      const canvas = await html2canvas(area, {
        scale: 2,
        backgroundColor: '#ffffff',
        width: fullWidth,
        windowWidth: fullWidth,
      });
      canvas.toBlob((blob) => {
        if (!blob) return;
        const url = URL.createObjectURL(blob);
        const link = document.createElement('a');
        link.download = `EPI_Microplan_${selectedYear}.png`;
        link.href = url;
        link.click();
        URL.revokeObjectURL(url);
      }, 'image/png');
    } catch {
      onNotify(
        lang === 'bn' ? 'ইমেজ ডাউনলোড করা যায়নি।' : 'Could not export image.',
        'error'
      );
    } finally {
      area.style.overflowX = prevOverflow;
      area.style.width = prevWidth;
    }
  };

  const handleExportExcel = () => {
    const headers = [t.mWord, t.mCenter, ...t.months];
    const dayNames = lang === 'bn' ? dayShortBn : dayShortEn;
    const rows = planRows.map((row) => [
      row.code,
      row.name,
      ...row.dates.map(
        (d) =>
          `${formatNum(d.getDate(), lang)}/${formatNum(d.getMonth() + 1, lang)} (${
            dayNames[d.getDay()]
          })`
      ),
    ]);
    const ws = XLSX.utils.aoa_to_sheet([
      [`${t.printMicroplanTitle} - ${t.yearPrefix}: ${formatNum(selectedYear, lang)}`],
      [],
      headers,
      ...rows,
    ]);
    const wb = XLSX.utils.book_new();
    XLSX.utils.book_append_sheet(wb, ws, `Microplan_${selectedYear}`);
    XLSX.writeFile(wb, `EPI_Microplan_${selectedYear}_${pairKey}.xlsx`);
  };

  const dayNames = lang === 'bn' ? dayShortBn : dayShortEn;
  const years = useMemo(() => {
    const list: number[] = [];
    for (let y = 2025; y <= 2150; y++) list.push(y);
    return list;
  }, []);

  return (
    <div className="bg-white border border-slate-200 rounded-3xl p-4 sm:p-6 shadow-xs space-y-4">
      {/* Toolbar */}
      <div className="flex flex-wrap items-center justify-between gap-3">
        <div className="flex items-center gap-2.5">
          <div className="w-10 h-10 rounded-xl bg-teal-50 text-teal-700 flex items-center justify-center shrink-0">
            <Table2 className="w-5 h-5" />
          </div>
          <h1 className="text-base sm:text-lg font-bold text-slate-900">{t.microplanHeading}</h1>
        </div>

        <div className="flex flex-wrap items-center gap-2">
          <button
            type="button"
            onClick={() => (isEditMode ? cancelEditMode() : enterEditMode())}
            className={`min-h-[42px] px-3.5 rounded-xl font-semibold text-xs sm:text-sm inline-flex items-center gap-1.5 border transition whitespace-nowrap ${
              isEditMode
                ? 'bg-slate-100 border-slate-300 text-slate-800'
                : 'bg-white border-teal-600 text-teal-800 hover:bg-teal-50'
            }`}
          >
            {isEditMode ? <X className="w-4 h-4" /> : <Pencil className="w-4 h-4" />}
            <span>{isEditMode ? t.cancelBtn : t.btnEditText}</span>
          </button>

          <button
            type="button"
            onClick={() => void handleDownloadImage()}
            className="min-h-[42px] px-3.5 rounded-xl bg-sky-600 hover:bg-sky-700 text-white font-semibold text-xs sm:text-sm inline-flex items-center gap-1.5 transition whitespace-nowrap"
          >
            <ImageIcon className="w-4 h-4" />
            <span>{t.imageBtn}</span>
          </button>

          <button
            type="button"
            onClick={handleExportExcel}
            className="min-h-[42px] px-3.5 rounded-xl bg-emerald-700 hover:bg-emerald-800 text-white font-semibold text-xs sm:text-sm inline-flex items-center gap-1.5 transition whitespace-nowrap"
          >
            <FileSpreadsheet className="w-4 h-4" />
            <span>{t.excelBtn}</span>
          </button>

          <button
            type="button"
            onClick={() => setConfirmResetOpen(true)}
            className="min-h-[42px] px-3.5 rounded-xl border border-rose-300 text-rose-700 hover:bg-rose-50 font-semibold text-xs sm:text-sm inline-flex items-center gap-1.5 transition whitespace-nowrap"
          >
            <RotateCcw className="w-4 h-4" />
            <span>{t.resetBtn}</span>
          </button>
        </div>
      </div>

      {/* Filters */}
      <div className="bg-teal-50/60 border border-teal-200/80 rounded-2xl p-3.5 grid grid-cols-1 sm:grid-cols-2 gap-3">
        <div>
          <label
            htmlFor="microplan-year"
            className="block text-xs font-bold text-teal-900 mb-1"
          >
            {t.yearSelectLabel}
          </label>
          <select
            id="microplan-year"
            value={selectedYear}
            onChange={(e) => {
              const yr = Number(e.target.value);
              setSelectedYear(yr);
              if (isEditMode) cancelEditMode();
            }}
            className="w-full min-h-[42px] px-3 rounded-xl border border-teal-300 bg-white text-slate-900 font-semibold text-sm tabular-nums"
          >
            {years.map((y) => (
              <option key={y} value={y}>
                {lang === 'bn' ? toBnNum(y) : y}
              </option>
            ))}
          </select>
        </div>

        <div>
          <label
            htmlFor="microplan-pair"
            className="block text-xs font-bold text-teal-900 mb-1"
          >
            {t.pairSelectLabel}
          </label>
          <select
            id="microplan-pair"
            value={pairKey}
            onChange={(e) => setPairKey(e.target.value as DayPairKey)}
            className="w-full min-h-[42px] px-3 rounded-xl border border-teal-300 bg-white text-slate-900 font-semibold text-sm"
          >
            <option value="mon-thu">{lang === 'bn' ? 'সোম - বৃহস্পতিবার' : 'Mon - Thu'}</option>
            <option value="sun-wed">{lang === 'bn' ? 'রবি - বুধবার' : 'Sun - Wed'}</option>
            <option value="sat-tue">{lang === 'bn' ? 'শনি - মঙ্গলবার' : 'Sat - Tue'}</option>
          </select>
        </div>
      </div>

      {/* Table Area */}
      <div
        ref={printAreaRef}
        className="overflow-x-auto border border-slate-200 rounded-2xl bg-white p-3"
      >
        <div className="text-center mb-3">
          <h2 className="font-bold text-teal-900 text-base">{t.printMicroplanTitle}</h2>
          <p className="text-xs text-slate-600 font-semibold tabular-nums">
            {t.yearPrefix}: {formatNum(selectedYear, lang)}
          </p>
        </div>

        <table
          ref={tableRef}
          className="min-w-[1100px] w-full border-collapse text-xs sm:text-sm tabular-nums"
        >
          <thead>
            <tr className="bg-teal-100 text-teal-950">
              <th className="sticky left-0 z-20 bg-teal-200 border border-slate-300 px-2 py-2.5 text-center font-bold w-20">
                {t.mWord}
              </th>
              <th className="border border-slate-300 px-3 py-2.5 text-left font-bold min-w-[200px]">
                {t.mCenter}
              </th>
              {t.months.map((mName) => (
                <th
                  key={mName}
                  className="border border-slate-300 px-2 py-2.5 text-center font-bold whitespace-nowrap"
                >
                  {mName}
                </th>
              ))}
            </tr>
          </thead>
          <tbody>
            {planRows.map((row) => (
              <tr key={row.code} className="hover:bg-slate-50/70">
                <td className="sticky left-0 z-10 bg-teal-50 border border-slate-300 px-2 py-2.5 text-center font-bold text-teal-900">
                  {row.code}
                </td>
                <td
                  onClick={() =>
                    isEditMode && setEditingCenter({code: row.code, name: row.name})
                  }
                  className={`border border-slate-300 px-3 py-2.5 text-left font-medium text-slate-900 ${
                    isEditMode ? 'cursor-pointer hover:bg-amber-50' : ''
                  }`}
                >
                  <span className="inline-flex items-center gap-1.5">
                    <span>{row.name}</span>
                    {isEditMode && <Pencil className="w-3.5 h-3.5 text-teal-700 shrink-0" />}
                  </span>
                </td>
                {row.dates.map((dObj, mIdx) => {
                  const isManual = Boolean(activeOverrides[row.code]?.[mIdx]);
                  let diffDays: number | null = null;
                  if (mIdx > 0) {
                    diffDays = Math.ceil(
                      Math.abs(dObj.getTime() - row.dates[mIdx - 1].getTime()) /
                        (1000 * 60 * 60 * 24)
                    );
                  }
                  const isWarn = diffDays !== null && diffDays < 28;

                  return (
                    <td
                      key={`${row.code}-${mIdx}`}
                      onClick={() =>
                        isEditMode &&
                        setEditingSession({
                          code: row.code,
                          monthIdx: mIdx,
                          dateStr: toIsoDateInput(dObj),
                        })
                      }
                      className={`border border-slate-300 px-2 py-2 text-center align-middle whitespace-nowrap ${
                        isManual ? 'bg-amber-50/80' : 'bg-white'
                      } ${isEditMode ? 'cursor-pointer hover:bg-amber-100/70' : ''}`}
                    >
                      <div className="font-bold text-slate-900">
                        {formatNum(dObj.getDate(), lang)}
                      </div>
                      <div className="text-[11px] text-slate-500">
                        {dayNames[dObj.getDay()]}
                      </div>
                      {diffDays !== null && (
                        <div
                          className={`text-[10px] font-semibold mt-0.5 ${
                            isWarn ? 'text-rose-700 bg-rose-50 rounded px-1' : 'text-teal-700'
                          }`}
                        >
                          {formatNum(diffDays, lang)} {lang === 'bn' ? 'দিন' : 'd'}
                        </div>
                      )}
                    </td>
                  );
                })}
              </tr>
            ))}
          </tbody>
        </table>
      </div>

      {isEditMode && (
        <div className="flex justify-end">
          <button
            type="button"
            onClick={handleSave}
            className="min-h-[46px] px-5 rounded-xl bg-emerald-700 hover:bg-emerald-800 text-white font-bold text-sm inline-flex items-center gap-2 shadow-sm transition"
          >
            <Save className="w-4 h-4" />
            <span>{t.savePlanBtnText}</span>
          </button>
        </div>
      )}

      {/* Edit Center Modal */}
      {editingCenter && (
        <div className="fixed inset-0 z-50 bg-slate-950/60 backdrop-blur-sm flex items-center justify-center p-4">
          <div className="w-full max-w-md bg-white rounded-3xl p-6 border border-slate-200 shadow-xl space-y-4">
            <h3 className="font-bold text-slate-900 text-base">
              {lang === 'bn'
                ? `কেন্দ্রের নাম পরিবর্তন (${editingCenter.code})`
                : `Edit Center Name (${editingCenter.code})`}
            </h3>
            <input
              type="text"
              value={editingCenter.name}
              onChange={(e) =>
                setEditingCenter({...editingCenter, name: e.target.value})
              }
              className="w-full min-h-[44px] px-3.5 py-2 rounded-xl border border-slate-300 text-slate-900 focus:outline-none focus:ring-2 focus:ring-teal-600"
            />
            <div className="flex justify-end gap-2">
              <button
                type="button"
                onClick={() => setEditingCenter(null)}
                className="min-h-[42px] px-4 rounded-xl border border-slate-300 text-slate-700 font-semibold text-sm"
              >
                {t.cancelBtn}
              </button>
              <button
                type="button"
                onClick={() => {
                  const trimmed = editingCenter.name.trim();
                  if (trimmed) {
                    setDraftCenters((prev) => ({
                      ...(prev ?? centerNames),
                      [editingCenter.code]: trimmed,
                    }));
                  }
                  setEditingCenter(null);
                }}
                className="min-h-[42px] px-4 rounded-xl bg-teal-700 text-white font-semibold text-sm"
              >
                {t.savePlanBtnText}
              </button>
            </div>
          </div>
        </div>
      )}

      {/* Edit Date Modal */}
      {editingSession && (
        <div className="fixed inset-0 z-50 bg-slate-950/60 backdrop-blur-sm flex items-center justify-center p-4">
          <div className="w-full max-w-md bg-white rounded-3xl p-6 border border-slate-200 shadow-xl space-y-4">
            <h3 className="font-bold text-slate-900 text-base">
              {editingSession.code} — {t.months[editingSession.monthIdx]}
            </h3>
            <input
              type="date"
              value={editingSession.dateStr}
              onChange={(e) =>
                setEditingSession({...editingSession, dateStr: e.target.value})
              }
              className="w-full min-h-[44px] px-3.5 py-2 rounded-xl border border-slate-300 text-slate-900 tabular-nums focus:outline-none focus:ring-2 focus:ring-teal-600"
            />
            <div className="flex justify-end gap-2">
              <button
                type="button"
                onClick={() => setEditingSession(null)}
                className="min-h-[42px] px-4 rounded-xl border border-slate-300 text-slate-700 font-semibold text-sm"
              >
                {t.cancelBtn}
              </button>
              <button
                type="button"
                onClick={() => {
                  if (editingSession.dateStr) {
                    setDraftOverrides((prev) => {
                      const next = structuredClone(prev ?? activeOverrides);
                      if (!next[editingSession.code]) next[editingSession.code] = {};
                      next[editingSession.code][editingSession.monthIdx] =
                        editingSession.dateStr;
                      return next;
                    });
                  }
                  setEditingSession(null);
                }}
                className="min-h-[42px] px-4 rounded-xl bg-teal-700 text-white font-semibold text-sm"
              >
                {t.savePlanBtnText}
              </button>
            </div>
          </div>
        </div>
      )}

      {/* Confirm Reset Modal */}
      {confirmResetOpen && (
        <div className="fixed inset-0 z-50 bg-slate-950/60 backdrop-blur-sm flex items-center justify-center p-4">
          <div className="w-full max-w-sm bg-white rounded-3xl p-6 border border-slate-200 shadow-xl space-y-4">
            <h3 className="font-bold text-slate-900 text-base">
              {lang === 'bn'
                ? 'ডিফল্ট শিডিউলে ফিরতে চান?'
                : 'Reset microplan to default?'}
            </h3>
            <p className="text-sm text-slate-600">
              {lang === 'bn'
                ? `${toBnNum(selectedYear)} সালের ম্যানুয়াল পরিবর্তনগুলো মুছে ফেলা হবে।`
                : `All manual date edits for ${selectedYear} will be cleared.`}
            </p>
            <div className="flex justify-end gap-2">
              <button
                type="button"
                onClick={() => setConfirmResetOpen(false)}
                className="min-h-[42px] px-4 rounded-xl border border-slate-300 text-slate-700 font-semibold text-sm"
              >
                {t.cancelBtn}
              </button>
              <button
                type="button"
                onClick={() => {
                  setDraftOverrides(null);
                  setIsEditMode(false);
                  onResetYear(selectedYear);
                  setConfirmResetOpen(false);
                  onNotify(
                    lang === 'bn'
                      ? 'মাইক্রোপ্লান ডিফল্ট অবস্থায় ফিরেছে।'
                      : 'Microplan reset to default.',
                    'info'
                  );
                }}
                className="min-h-[42px] px-4 rounded-xl bg-rose-600 text-white font-semibold text-sm"
              >
                {t.resetBtn}
              </button>
            </div>
          </div>
        </div>
      )}
    </div>
  );
};
